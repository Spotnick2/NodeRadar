"""Generate Data/MinimapTiles.lua: the minimap's tile textures by FileDataID (#117).

The client draws the minimap from per-continent tiles, world/minimaps/<map>/map<x>_<y>.blp,
x running east and y south, each 1600/3 yards square. The scan's stand-in (ScanFace.lua) draws
them by FileDataID. The IDs come from the wowdev community listfile
(github.com/wowdev/wow-listfile, community-listfile.csv: "<fileID>;<path>" lines).

    python -I Tools/export_tiles.py <community-listfile.csv> [--release <tag>] [--maps <Map.csv>] [--write]

--maps: Forever's Map table (References/Forever/db/forever-map-<build>.csv, from wago.py): every
open-world map (InstanceType 0) with tiles in the listfile is added, its Directory the folder
(Zephras Isle, Hyjal Crater, ...). Without it, the two continents only. Without --write it prints
the counts only. The output is generated: never edit it by hand.
"""

import csv

import re
import sys
from pathlib import Path

# UnitPosition's instance ID -> the listfile's folder (the continents; --maps adds Forever's others).
MAPS = {0: "azeroth", 1: "kalimdor"}
NAMES = {0: "Eastern Kingdoms", 1: "Kalimdor"}


def forever_maps(path):
    """Every open-world map in Forever's Map table: {id: folder}, {id: name}."""
    maps, names = {}, {}
    with open(path, encoding="utf-8") as f:
        for row in csv.DictReader(f):
            if row.get("InstanceType") == "0" and row.get("Directory"):
                inst = int(row["ID"])
                maps[inst] = row["Directory"].lower()
                names[inst] = row.get("MapName_lang") or row["Directory"]
    return maps, names
PATTERN = re.compile(r"^(\d+);world/minimaps/([a-z0-9_]+)/map(\d+)_(\d+)\.blp$")
PER_LINE = 8


def read(listfile):
    folders = {name: inst for inst, name in MAPS.items()}
    tiles = {inst: {} for inst in MAPS}
    with open(listfile, encoding="utf-8", errors="replace") as f:
        for line in f:
            m = PATTERN.match(line.strip().lower())
            if not m or m.group(2) not in folders:
                continue
            fid, x, y = int(m.group(1)), int(m.group(3)), int(m.group(4))
            if not (0 <= x < 64 and 0 <= y < 64):
                continue
            key = x * 64 + y
            inst = folders[m.group(2)]
            # One path, one ID: a second ID for a path keeps the higher (the newer file).
            tiles[inst][key] = max(fid, tiles[inst].get(key, 0))
    return tiles


def render(tiles, release):
    out = [
        "-- Data/MinimapTiles.lua: GENERATED by Tools/export_tiles.py, never edit by hand (#117).",
        f"-- The minimap's tile textures by FileDataID, from the wowdev community listfile ({release}).",
        "-- NodeRadar.MINIMAP_TILES[instance][x * 64 + y] = fileID: x runs east, y south, each tile",
        "-- 1600/3 yards; instance as UnitPosition returns it (0 Eastern Kingdoms, 1 Kalimdor, and",
        "-- Forever's other open-world maps by their Map ID).",
        "",
        "NodeRadar = NodeRadar or {}",
        "NodeRadar.MINIMAP_TILES = {",
    ]
    for inst in sorted(tiles):
        out.append(f"    [{inst}] = {{ -- {NAMES.get(inst, MAPS[inst])} ({MAPS[inst]}), {len(tiles[inst])} tiles")
        keys = sorted(tiles[inst])
        for i in range(0, len(keys), PER_LINE):
            row = ",".join(f"[{k}]={tiles[inst][k]}" for k in keys[i:i + PER_LINE])
            out.append("        " + row + ",")
        out.append("    },")
    out.append("}")
    return "\n".join(out) + "\n"


def main(argv):
    args = [a for a in argv if not a.startswith("--")]
    if not args:
        print(__doc__)
        return 2
    release = "unknown release"
    if "--release" in argv:
        release = argv[argv.index("--release") + 1]
        args = [a for a in args if a != release]
    if "--maps" in argv:
        maps_csv = argv[argv.index("--maps") + 1]
        args = [a for a in args if a != maps_csv]
        found, names = forever_maps(maps_csv)
        MAPS.update(found)
        NAMES.update(names)
    tiles = read(args[0])
    if not (tiles.get(0) and tiles.get(1)):
        print("a continent has no tiles: is this the community listfile?")
        return 1
    for inst in [i for i in tiles if not tiles[i]]:
        del tiles[inst]                                   # a map without tiles in the listfile
    for inst in sorted(tiles):
        print(f"{NAMES.get(inst, MAPS[inst])} ({MAPS[inst]}, instance {inst}): {len(tiles[inst])} tiles")
    if "--write" in argv:
        target = Path(__file__).resolve().parent.parent / "Data" / "MinimapTiles.lua"
        target.write_text(render(tiles, release), encoding="utf-8", newline="\n")
        print(f"wrote {target} ({target.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
